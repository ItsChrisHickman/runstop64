/**
 * Builds games/karnath/src/pictures.ts: The Staff of Karnath's rooms as pieces (c64kit's pendragon/room.ts),
 * decoded from the game's own room maps by games/shared/pendragon/decode.ts (re/README.md, "The rooms as
 * pieces"):
 *
 * - the maps: each level is a strip of rooms drawn side by side, kept as three blocks of 40 columns × 20
 *   rows ($400 apart; $7FE0-$7FEB point into them), and the screen shows 40 columns of the strip scrolling
 *   along it ($7000 the lower floor's three levels, $9400 the upper floor's three, the dungeons' and Karn's
 *   abode's swapped in over the first: re/README.md, "Travel back"). So a picture here is a whole strip, 120
 *   × 20 characters, and the band shows a window of it;
 * - the maps are the game's as it starts, got by the game's own changes of mode ($2E33, $1199, $12E1: the
 *   transitions src/travel.ts uses) from the title's snapshot, so nothing taken or opened is in them;
 * - the lower floor's rooms are 16 rows from row 4 (a top edge, the walls, the floor, its front edge), the 4
 *   rows over them the floor of the room beyond the back wall, seen over its top; the upper floor's are the
 *   first 16 rows, the 4 rows under their front edge the top of what's kept below: one face under the floor;
 * - the castle is drawn in the character set at $3800, the dungeons and the abode in their own.
 *
 *   nice -n 15 node tools/test.mjs games/karnath/re/pictures.ts [out-dir: each strip's pieces as PNGs]
 */
import fs from 'node:fs';
import { NativeHost } from '../../shared/native/host';
import { unpackState } from '../../../packages/c64kit/src/c64/machine';
import { pixelPieces, type RoomPicture } from '../../../packages/c64kit/src/pendragon/room';
import { decodePictures, type PictureSource } from '../../shared/pendragon/decode';
import { rgbPng } from '../../../tools/probe/render';
import { C64_PALETTE } from '../../../packages/c64kit/src/palette';
import { port } from '../src/native';
import { toMode } from '../src/travel';
import { STRIPS } from '../src/strips';
import { karnathRules } from '../src/hd';

const outDir = process.argv[2];
const COLS = 40, BLOCKS = 3, ROWS = 20;
/** The upper floor's rooms are 16 rows (a top edge in row 0, the floor's front edge in row 15); under them the 4 rows are the top of what's kept below. */
const UPPER_FRONT = 15;
const g = new NativeHost(port, unpackState(new Uint8Array(fs.readFileSync('games/karnath/assets/karnath-title.state'))));
const { ram } = g.m;
ram[0x3219] = 0;

// each strip's three blocks side by side (a row of the strip: the blocks' row after row), in the order of the modes the game goes through from the lower floor
const sources: PictureSource[] = [];
const sets: Uint8Array[] = [];
for (const mode of [1, 0, 0xff, 0xfe]) {
  toMode(ram, mode);
  const charset = ram.slice(0x3800, 0x4000);
  for (const [id, s] of STRIPS.entries()) {
    if (s.mode !== mode) continue;
    const codes = new Uint8Array(COLS * BLOCKS * ROWS);
    for (let b = 0; b < BLOCKS; b++) for (let r = 0; r < ROWS; r++) for (let c = 0; c < COLS; c++) codes[r * COLS * BLOCKS + b * COLS + c] = ram[(s.base << 8) + b * 0x400 + r * COLS + c];
    sources.push({ id, variant: 0, cols: COLS * BLOCKS, rows: ROWS, codes, charset, set: s.mode >= 0xfe ? 'dungeon' : 'castle', front: s.mode === 1 ? UPPER_FRONT : undefined });
    sets.push(charset);
  }
}
sources.sort((a, b) => a.id - b.id);
const pictures = decodePictures(sources, karnathRules);

const hex = (b: Uint8Array) => Buffer.from(b).toString('hex');
const pieceText = (p: RoomPicture['pieces'][number]) => p.kind === 'floor' ? `{ kind: 'floor', height: ${p.height} }` : p.kind === 'side' ? `{ kind: 'side', slope: ${p.slope}, at: ${p.at} }` : `{ kind: '${p.kind}', depth: ${p.depth} }`;
let out = `// Generated by games/karnath/re/pictures.ts from the game's own room maps: do not edit by hand.
import { hexBytes, type RoomPictures } from 'c64kit';

/**
 * The Staff of Karnath's rooms as pieces (c64kit's pendragon/room.ts): each level's strip of rooms (a
 * picture, its id the strip's index in src/strips.ts: the band shows a window of it, scrolling along),
 * decoded into where each piece of it stands.
 */
export const PICTURES: RoomPictures = {
  pictures: [
`;
for (const p of pictures) {
  out += `    {\n      id: ${p.id}, variant: ${p.variant}, cols: ${p.cols}, rows: ${p.rows},\n`;
  out += `      codes: hexBytes('${hex(p.codes)}'),\n`;
  out += `      cells: hexBytes('${hex(p.cells)}'),\n`;
  out += `      pieces: [\n${p.pieces.map((q) => `        ${pieceText(q)},`).join('\n')}\n      ],\n`;
  out += `      parts: Uint32Array.from([${Array.from(p.parts).join(', ')}]),\n    },\n`;
}
out += `  ],\n  beside: [],\n};\n`;
fs.writeFileSync('games/karnath/src/pictures.ts', out);
console.log(`games/karnath/src/pictures.ts: ${pictures.length} pictures, ${pictures.reduce((n, p) => n + p.pieces.length, 0)} pieces`);
for (const p of pictures) {
  const count = (k: string) => p.pieces.filter((q) => q.kind === k).length;
  console.log(`  ${STRIPS[p.id].label}: ${count('wall')} walls (${p.pieces.filter((q) => q.kind === 'wall').map((q) => q.kind === 'wall' ? q.depth : 0).join(', ')}), ${count('side')} side walls, ${count('thing')} things, ${p.parts.length / 3} cells in parts`);
}

// to look at: each strip drawn, tinted by its pieces (walls blue, side walls green, things warm, each its own,
// the floor as drawn), and under it each pixel's depth (near light, far dark)
if (outDir) {
  fs.mkdirSync(outDir, { recursive: true });
  for (const [k, p] of pictures.entries()) {
    const set = sets[k], W = p.cols * 8, H = p.rows * 8, rgb = new Float32Array(W * H * 2 * 3), pix = pixelPieces(p);
    for (let y = 0; y < H; y++) for (let x = 0; x < W; x++) {
      const code = p.codes[(y >> 3) * p.cols + (x >> 3)], v = (set[code * 8 + (y & 7)] >> (6 - (x & 6))) & 3;
      const c = C64_PALETTE[[0, 8, 9, 7][v]], piece = p.pieces[pix[y * W + x]], id = pix[y * W + x];
      const tint = piece.kind === 'floor' ? [1, 1, 1] : piece.kind === 'wall' ? [0.55, 0.7, 1.3] : piece.kind === 'side' ? [0.6, 1.3, 0.6] : [1.3, 0.5 + ((id * 37) % 7) / 10, 0.4 + ((id * 53) % 5) / 8];
      const o = (y * W + x) * 3;
      rgb[o] = Math.min(1, ((c >> 16) / 255 + 0.15) * tint[0]); rgb[o + 1] = Math.min(1, (((c >> 8) & 255) / 255 + 0.15) * tint[1]); rgb[o + 2] = Math.min(1, ((c & 255) / 255 + 0.15) * tint[2]);
      const z = piece.kind === 'floor' ? H - y - 0.5 - piece.height : piece.kind === 'side' ? piece.slope * (x + 0.5) - piece.at : piece.depth;
      const d = Math.max(0, Math.min(1, 1 - z / 140)), q = ((H + y) * W + x) * 3;
      rgb[q] = d; rgb[q + 1] = d * (piece.kind === 'thing' ? 0.6 : 1); rgb[q + 2] = d * (piece.kind === 'floor' ? 0.6 : 1);
    }
    rgbPng(`${outDir}/${STRIPS[p.id].label}.png`, rgb, W, H * 2, 1);
  }
}
