/**
 * Writes the rebuild's data modules (games/montymole/src/data/) from the original's tape (the game block's 64K image): the
 * sprites, Monty's frames, the title picture, the font, the texts, the jump arc, the coal values and the two tunes. The rooms are
 * made by re/rooms.ts. The output is committed (it is the data, not the program: no code of the original, no tape, no ROM).
 *
 *   nice -n 15 node tools/test.mjs games/montymole/re/extract.ts [tape]
 */
import fs from 'node:fs';
import { GLYPH_CHARS } from '../src/letters';
import { bytesOf, ENDING_AT, GAME_OVER_AT, imageFromTape, LIVES_SPOT, MENU, SCORE_SPOT, SPANS, textRecord, verse, type Span, type TextRecord } from './original';

const [tapeFile = 'games/montymole/build/montymole.tap'] = process.argv.slice(2);
const image = imageFromTape(new Uint8Array(fs.readFileSync(tapeFile)));
const OUT = 'games/montymole/src/data';

const hex = (b: Uint8Array) => Array.from(b, (v) => v.toString(16).padStart(2, '0')).join('');
const addr = (n: number) => `$${n.toString(16).toUpperCase()}`;

function constant(name: string, span: Span): string {
  return `/** ${span.name} (${addr(span.at)}-${addr(span.at + span.length - 1)}, ${span.length} bytes). */\nexport const ${name}: string =\n  '${hex(bytesOf(image, span))}';\n`;
}
const head = (what: string) => `// Generated by games/montymole/re/extract.ts from the original (${what}): do not edit.\n// Bytes as hex strings; src/data.ts turns them into typed tables.\n\n`;
const chars = (codes: readonly number[]): string => codes.map((c) => GLYPH_CHARS.charAt(c)).join('');

fs.mkdirSync(OUT, { recursive: true });

fs.writeFileSync(`${OUT}/graphics-data.ts`, head('the tape\'s game block')
  + constant('SPRITES_HEX', SPANS.sprites) + '\n' + constant('MONTY_HEX', SPANS.monty) + '\n' + constant('DEATH_SPRITE_HEX', SPANS.deathSprite) + '\n' + constant('TITLE_HEX', SPANS.title));

fs.writeFileSync(`${OUT}/tables-data.ts`, head('the tape\'s game block')
  + constant('FONT_HEX', SPANS.font) + '\n' + constant('JUMP_ARC_HEX', SPANS.jumpArc) + '\n' + constant('COAL_HEX', SPANS.coal));

fs.writeFileSync(`${OUT}/music-data.ts`, head('the tape\'s game block')
  + constant('TITLE_TUNE_HEX', SPANS.titleTune) + '\n' + constant('DEATH_TUNE_HEX', SPANS.deathTune));

/** One text record as source. */
function spot(name: string, r: TextRecord, text: string): string {
  return `export const ${name} = { column: ${r.column}, pixelRow: ${r.pixelRow}, colour: 0x${r.colour.toString(16)}, attrRow: ${r.attrRow}, text: ${JSON.stringify(text)} } as const;\n`;
}
const menu = MENU.map((s) => textRecord(image, s));
const score = textRecord(image, SCORE_SPOT);
const lives = textRecord(image, LIVES_SPOT);
const lines = (at: number) => verse(image, at).map((l) => chars(l));
fs.writeFileSync(`${OUT}/texts-data.ts`, head('the tape\'s game block')
  + `/** A line of text the game prints in a fixed place: its character column, the pixel row of its top, its colour attribute, the attribute row, and its words. */\n`
  + `export interface TextLine { readonly column: number; readonly pixelRow: number; readonly colour: number; readonly attrRow: number; readonly text: string }\n\n`
  + `/** The options menu's five lines ($8122, $826B): OPTIONS and the four choices. */\n`
  + `export const MENU_LINES: readonly TextLine[] = [\n${menu.map((r) => `  { column: ${r.column}, pixelRow: ${r.pixelRow}, colour: 0x${r.colour.toString(16)}, attrRow: ${r.attrRow}, text: ${JSON.stringify(chars(r.codes))} },`).join('\n')}\n];\n\n`
  + `/** The score line ($9212): its place; the five digits (most significant first) follow the words. */\n`
  + spot('SCORE_LINE', score, chars(score.codes.slice(0, 7))) + '\n'
  + `/** The lives line ($94B6): its place; the digit follows the words. */\n`
  + spot('LIVES_LINE', lives, chars(lives.codes.slice(0, 7))) + '\n'
  + `/** The game-over verse ($F04B), a line each (a blank line is a gap). */\nexport const GAME_OVER_VERSE: readonly string[] = ${JSON.stringify(lines(GAME_OVER_AT), null, 2)};\n\n`
  + `/** The ending verse ($5CE1), a line each. */\nexport const ENDING_VERSE: readonly string[] = ${JSON.stringify(lines(ENDING_AT), null, 2)};\n`);

const word = (at: number): number => (image[at] ?? 0) | ((image[at + 1] ?? 0) << 8);
fs.writeFileSync(`${OUT}/sounds-data.ts`, head('the tape\'s game block')
  + `/** The effects are calls of the ROM's BEEPER with DE and HL, the operands read from the code: the footstep and jump tick starts at this pitch ($8496, and goes up a step a pass while Monty rises, down while he falls), DE 1; the thud of the crusher ($8E22: LD DE, LD HL); the pick-up beep of coal, an object and a tool touch ($9568, $93D0, $92EE: all the same). */\n`
  + `export const STEP_PITCH_START = ${word(0x8496)};\n`
  + `export const STEP_CYCLES = 1;\n`
  + `export const THUD = { de: ${word(0x8e23)}, hl: ${word(0x8e26)} } as const;\n`
  + `export const PICKUP = { de: ${word(0x9569)}, hl: ${word(0x956c)} } as const;\n`);

console.log(`wrote ${OUT}: ${menu.length} menu lines, ${lines(GAME_OVER_AT).length} game over lines, ${lines(ENDING_AT).length} ending lines`);
