/**
 * The routes for the reward show, found by playing (src/ending.ts uses them; src/ending-routes.ts is what this writes).
 *
 * For each room of the montage, in the order of the game: a `SteadyGame` (the same key plays the same game, so a plan tried on a copy is what the game then does) put at the room's
 * way in (the place the last room's way on came out at) with the coal all there, as the opening scene's gift leaves it (but for `taken` pieces taken elsewhere in a gate's room,
 * so that its piece makes the gate's count and the gate opens), and the test suite's bot (test/bot.ts: the goals of each room, looked for by a search on copies of the game) playing
 * it, pass by pass: every piece of the room, then the way on. The keys of each pass are written down as the shared pilot reads them (`shared/ending/pilot.ts`).
 * A room the bot cannot play ends the list there (the way in of the next is not known), and is said.
 *
 *   nice -n 15 node tools/test.mjs games/montymole/re/ending/route.ts [first-last]
 */
import fs from 'node:fs';
import { routeText, type Move } from '../../../shared/ending/pilot';
import { Key } from '../../src/controls';
import { GATES } from '../../src/gates';
import { sceneGame, SCENE_ROOMS } from '../../src/ending';
import type { SceneRoute } from '../../src/ending-routes';
import { NEXT_ROOM, Goals, piecesLeft, Planner } from '../../test/bot';

/** The stick's token for each way the bot's keys go (a direction, with the jump held or not). */
function moveOf(keys: number): Move {
  const direction = keys & (Key.up | Key.down | Key.left | Key.right);
  const token = direction === 0 ? '.' : direction === Key.up ? '^' : direction === Key.down ? 'v' : direction === Key.left ? '<' : direction === Key.right ? '>' : null;
  if (token === null) throw new Error(`keys ${keys} are not a move`);
  if ((keys & Key.jump) === 0) return token;
  return token === '.' ? 'J' : token === '^' ? 'J^' : token === 'v' ? 'Jv' : token === '<' ? 'J<' : 'J>';
}

const range = (process.argv[2] ?? '').split('-').map(Number);
const first = Number.isInteger(range[0]) ? range[0] ?? 0 : 0;
const last = Number.isInteger(range[1]) ? range[1] ?? Infinity : Infinity;
const rooms = SCENE_ROOMS.filter((r) => r >= first && r <= last);

const found: Record<number, SceneRoute> = {};
/** Where he comes into the room: room 0 from the opening scene; the others where the last room's way on put him. */
let at = { x: 0x18, y: 0x27 };
for (const room of rooms) {
  const gate = GATES.find((g) => g.room === room);
  const start = { key: 1, x: at.x, y: at.y, taken: gate === undefined ? 0 : gate.count - 1 };
  const game = sceneGame(room, start);
  const goals = new Goals(new Planner(game), (message) => console.log(`   room ${room}: ${message}`));
  const t0 = performance.now();
  try {
    for (let left = piecesLeft(game, room); left.length > 0; left = piecesLeft(game, room)) goals.must(`a piece of coal (${left.join(', ')} left)`, { kind: 'pieces', ids: left });
    goals.must('the way on', { kind: 'room', room: NEXT_ROOM[room] ?? 21 });
  } catch (error) {
    console.log(`room ${room}: ${error instanceof Error ? error.message : String(error)}`);
    break;
  }
  const route = routeText(goals.keys.map(moveOf));
  console.log(`room ${room}: ${goals.keys.length} passes (${(goals.keys.length / 25).toFixed(0)} s), in ${((performance.now() - t0) / 1000).toFixed(0)} s`);
  found[room] = { ...start, route };
  at = { x: game.arrivalX, y: game.arrivalY };
}
const body = Object.entries(found).map(([room, r]) => `  ${room}: { key: ${r.key}, x: ${r.x}, y: ${r.y}, taken: ${r.taken}, route: '${r.route}' },`).join('\n');
fs.writeFileSync('games/montymole/src/ending-routes.ts', `// Generated by games/montymole/re/ending/route.ts: do not edit by hand.
/** Where a scene of the reward show begins: the key of the game's numbers (\`SteadyGame\`), the place Monty comes into the room, and how many pieces of coal are taken elsewhere. */
export interface SceneStart { readonly key: number; readonly x: number; readonly y: number; readonly taken: number }
/** A room's route for the show: its start, and the keys of each pass as the shared pilot reads them (\`shared/ending/pilot.ts\`: a stick, a run at a time). */
export interface SceneRoute extends SceneStart { readonly route: string }
export const ROUTES: Readonly<Record<number, SceneRoute>> = {
${body}
};
`);
