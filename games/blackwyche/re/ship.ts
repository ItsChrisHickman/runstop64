/**
 * Builds games/blackwyche/src/ship.ts: the galleon as the game lays it out, for the pause
 * screen's map, from the game's own data and code (re/README.md, "The ship"):
 *
 * - each deck's two long parts ($9D78 deck 1-5, $1ECD part 0/1): nine screen-wide panels
 *   each, from the table at $6E43 (18 per deck; $73 a door, $76 the left end, $79 the right);
 *   one door ($6E8C, deck 5's fore part) is drawn as wall until the game opens it ($12A5);
 * - the halls between their ends ($1ECD 2/3): the room $148D gives each, two panels each
 *   ($1504/$150A; he comes in at panel 1 or 2);
 * - the cabins behind the doors: the game's own choice ($9DC2) run for every deck, part and
 *   door, giving the cabin's room ($341C) and its picture ($1ECF);
 * - the ways between decks, which keep the part and door: a hole in a cabin's floor (its
 *   picture has the chars $1360 takes down, $19/$2A) over a ladder in the cabin below (the
 *   char it takes up, $14), and the trapdoors (the cabins whose block code drops him: it
 *   sets $342A, which $2DAD takes down a deck).
 *
 *   nice -n 15 node tools/test.mjs games/blackwyche/re/ship.ts
 */
import fs from 'node:fs';
import { unpackState } from '../../../packages/c64kit/src/c64/machine';
import { NativeHost } from '../../shared/native/host';
import { port } from '../src/native';
import { ROOMS } from '../src/rooms';
import * as engine from '../src/gen/engine';

const g = new NativeHost(port, unpackState(new Uint8Array(fs.readFileSync('games/blackwyche/assets/blackwyche-title.state'))));
const ram = g.m.ram;
const hex = (n: number) => `0x${n.toString(16).padStart(2, '0')}`;

// the decks' panels
const panels: number[][][] = [];
for (let d = 1; d <= 5; d++) panels.push([0, 1].map((p) => Array.from(ram.subarray(0x6e43 + 18 * (d - 1) + 9 * p, 0x6e43 + 18 * (d - 1) + 9 * p + 9))));

// the halls: their rooms ($148D) and panels ($1504, $150A: 0 and 3 are their ends)
const halls: { deck: number; part: number; room: number; panels: number[] }[] = [];
for (let d = 1; d <= 5; d++) for (const p of [2, 3]) {
  ram[0x9d78] = d; ram[0x1ecd] = p;
  g.callNative(() => engine.r_148d());
  const at = p === 2 ? 0x1504 : 0x150a;
  halls.push({ deck: d, part: p, room: ram[0x341c], panels: [ram[at + 1], ram[at + 2]] });
}

// the cabins: the game's own choice of cabin by deck, part and door ($9DC2)
interface Cabin { deck: number; part: number; door: number; room: number; picture: number; hidden: boolean }
const cabins: Cabin[] = [];
for (let d = 1; d <= 5; d++) for (const p of [0, 1]) for (let door = 0; door < 9; door++) {
  ram[0x9d78] = d; ram[0x1ecd] = p; ram[0x1f88] = door; ram[0x341c] = 0xff;
  g.callNative(() => engine.r_9dc2());
  if (ram[0x341c] === 0xff) continue;
  cabins.push({ deck: d, part: p, door, room: ram[0x341c], picture: ram[0x1ecf], hidden: panels[d - 1][p][door] !== 0x73 });
}

// what's in a cabin's picture (a 40 x 16 char map at its page)
const hasChar = (page: number, chars: number[]) => {
  for (let i = 0; i < 40 * 16; i++) if (chars.includes(ram[page * 256 + i])) return true;
  return false;
};
// the rooms whose block drops him a deck (sets $342A): the block versions with `sta $342A`, and where each is kept ($9D7A)
const homeOf = (room: number) => ram[0x9d7a + 2 * (room - 1)] | (ram[0x9d7b + 2 * (room - 1)] << 8);
const versionAt = (home: number) => ROOMS.find((v) => {
  const runs = Object.values(v.code).flat();
  return runs.length > 0 && runs.every(([a, h]) => { for (let i = 0; i < h.length; i += 2) if (ram[home + a - 0x6000 + i / 2] !== parseInt(h.slice(i, i + 2), 16)) return false; return true; });
});
const drops = (room: number) => {
  const v = versionAt(homeOf(room));
  return !!v && Object.values(v.code).flat().some(([, h]) => /^(..)*8d2a34/.test(h));
};

const ways: { from: number; to: number; kind: 'ladder' | 'trapdoor' }[] = [];
cabins.forEach((c, i) => {
  const below = cabins.findIndex((b) => b.deck === c.deck + 1 && b.part === c.part && b.door === c.door);
  if (below < 0) return;
  if (hasChar(c.picture, [0x19, 0x2a]) && hasChar(cabins[below].picture, [0x14])) ways.push({ from: i, to: below, kind: 'ladder' });
  else if (drops(c.room)) ways.push({ from: i, to: below, kind: 'trapdoor' });
});

const out = `// Generated by games/blackwyche/re/ship.ts from the game's own data and code: do not edit by hand.
/** Each deck's (1-5) two parts' nine panels ($6E43): $73 a door, $76 the left end, $79 the right end. */
export const PANELS: number[][][] = [
${panels.map((d) => `  [${d.map((p) => `[${p.map(hex).join(', ')}]`).join(', ')}],`).join('\n')}
];
/** The halls between the parts' ends ($1ECD 2 and 3): the room ($148D) and their two panels. */
export const HALLS: { deck: number; part: number; room: number; panels: number[] }[] = [
${halls.map((h) => `  { deck: ${h.deck}, part: ${h.part}, room: ${hex(h.room)}, panels: [${h.panels.map(hex).join(', ')}] },`).join('\n')}
];
/** The cabins behind the doors ($9DC2): room ($341C) and picture ($1ECF); hidden: the door is wall until the game opens it. */
export const CABINS: { deck: number; part: number; door: number; room: number; picture: number; hidden: boolean }[] = [
${cabins.map((c) => `  { deck: ${c.deck}, part: ${c.part}, door: ${c.door}, room: ${hex(c.room)}, picture: ${hex(c.picture)}, hidden: ${c.hidden} },`).join('\n')}
];
/** The ways down a deck (indexes into CABINS, the part and door kept): a hole over a ladder (both ways), or a trapdoor. */
export const WAYS: { from: number; to: number; kind: 'ladder' | 'trapdoor' }[] = [
${ways.map((w) => `  { from: ${w.from}, to: ${w.to}, kind: '${w.kind}' }, // ${hex(cabins[w.from].room)} -> ${hex(cabins[w.to].room)}`).join('\n')}
];
`;
fs.writeFileSync('games/blackwyche/src/ship.ts', out);
console.log(`${cabins.length} cabins, ${halls.length} halls, ${ways.length} ways between decks`);
for (const w of ways) console.log(`  ${w.kind}: deck ${cabins[w.from].deck} ${hex(cabins[w.from].room)} -> deck ${cabins[w.to].deck} ${hex(cabins[w.to].room)}`);
