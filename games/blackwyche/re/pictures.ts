/**
 * Builds games/blackwyche/src/pictures.ts: Blackwyche's rooms as pieces (c64kit's pendragon/room.ts),
 * decoded from the game's own room pictures by games/shared/pendragon/decode.ts (re/README.md, "The
 * rooms as pieces"):
 *
 * - the pictures: 40 × 17 characters each at a page of their own (the 16 rows of the room and the
 *   floor's front edge), which $26AA copies to the screen's rows 4-20 (from $1532's page, from
 *   column $1531 on: a part of the next one beside it as the deck scrolls): the decks' four ($70 a
 *   stretch of deck, $73 one with a door, $76 the left end, $79 the right; the table at $6E43), the
 *   halls' ($7C/$7F, $82/$85: $1504, $150A) and the cabins' ($82 on its left, its own ($1ECF, $9DC2), $85
 *   on its right: $10A7);
 * - the decks' first four rows are deck 1's (the sky and the sea over the rail) or the lower decks'
 *   (the deck above): $131F swaps them with $B200, $B2A0 and $B340, the same rows for $70 and $73;
 * - the decks are drawn in the character set at $3800; the halls and cabins in the one at $B800,
 *   which $1082 swaps in;
 * - which stand side by side: the decks' parts ($6E43, src/ship.ts), a hall's four screens ($1504,
 *   $150A: $82 and $85 either side of its two), a cabin's three.
 *
 *   nice -n 15 node tools/test.mjs games/blackwyche/re/pictures.ts [out-dir: each picture's pieces as PNGs]
 */
import fs from 'node:fs';
import { unpackState } from '../../../packages/c64kit/src/c64/machine';
import { pixelPieces, type RoomPicture } from '../../../packages/c64kit/src/pendragon/room';
import { decodePictures, type PictureSource } from '../../shared/pendragon/decode';
import { rgbPng } from '../../../tools/probe/render';
import { C64_PALETTE } from '../../../packages/c64kit/src/palette';
import { CABINS, PANELS } from '../src/ship';
import { blackwycheRules } from '../src/hd';

const ram = unpackState(new Uint8Array(fs.readFileSync('games/blackwyche/assets/blackwyche-title.state'))).ram;
const outDir = process.argv[2];
const COLS = 40, ROWS = 17, DECKS = [0x70, 0x73, 0x76, 0x79], OTHERS = [0x7c, 0x7f, 0x82, 0x85, 0x88, 0x8b, 0x8e, 0xa0, 0xa3, 0xa6, 0xac, 0xaf];
const deckSet = ram.slice(0x3800, 0x4000), cabinSet = ram.slice(0xb800, 0xc000);
const picture = (page: number) => ram.slice(page * 256, page * 256 + COLS * ROWS);
// (the lower decks' first four rows, $131F)
const LOWER: Record<number, number> = { 0x70: 0xb200, 0x73: 0xb200, 0x76: 0xb2a0, 0x79: 0xb340 };
const sources: PictureSource[] = [];
for (const id of DECKS) {
  sources.push({ id, variant: 0, cols: COLS, rows: ROWS, codes: picture(id), charset: deckSet, set: 'decks' });
  const lower = picture(id);
  lower.set(ram.subarray(LOWER[id], LOWER[id] + 0xa0));
  sources.push({ id, variant: 1, cols: COLS, rows: ROWS, codes: lower, charset: deckSet, set: 'decks' });
}
for (const id of OTHERS) sources.push({ id, variant: 0, cols: COLS, rows: ROWS, codes: picture(id), charset: cabinSet, set: 'cabins' });
const pictures = decodePictures(sources, blackwycheRules);

// side by side
const beside = new Set<string>();
for (const deck of PANELS) for (const part of deck) for (let k = 0; k + 1 < part.length; k++) beside.add(`${part[k]},${part[k + 1]}`);
// (a hall's four screens, $1504 and $150A: its two panels between the ones it's entered from)
for (const at of [0x1504, 0x150a]) for (let k = 0; k < 3; k++) beside.add(`${ram[at + k]},${ram[at + k + 1]}`);
for (const c of CABINS) { beside.add(`${0x82},${c.picture}`); beside.add(`${c.picture},${0x85}`); }
const pairs = [...beside].map((s) => s.split(',').map(Number)).sort((a, b) => a[0] - b[0] || a[1] - b[1]);

const hex = (b: Uint8Array) => Buffer.from(b).toString('hex');
const h2 = (n: number) => `0x${n.toString(16).padStart(2, '0')}`;
const pieceText = (p: RoomPicture['pieces'][number]) => p.kind === 'floor' ? `{ kind: 'floor', height: ${p.height} }` : p.kind === 'side' ? `{ kind: 'side', slope: ${p.slope}, at: ${p.at} }` : `{ kind: '${p.kind}', depth: ${p.depth} }`;
let out = `// Generated by games/blackwyche/re/pictures.ts from the game's own room pictures: do not edit by hand.
import { hexBytes, type RoomPictures } from 'c64kit';

/**
 * Blackwyche's rooms as pieces (c64kit's pendragon/room.ts): each picture the game draws a room from
 * (its page; variant 1: the decks' as the lower decks have them), decoded into where each piece of it
 * stands; and which pictures stand side by side (the decks' parts, the halls, the cabins).
 */
export const PICTURES: RoomPictures = {
  pictures: [
`;
for (const p of pictures) {
  out += `    {\n      id: ${h2(p.id)}, variant: ${p.variant}, cols: ${p.cols}, rows: ${p.rows},\n`;
  out += `      codes: hexBytes('${hex(p.codes)}'),\n`;
  out += `      cells: hexBytes('${hex(p.cells)}'),\n`;
  out += `      pieces: [\n${p.pieces.map((q) => `        ${pieceText(q)},`).join('\n')}\n      ],\n`;
  out += `      parts: Uint32Array.from([${Array.from(p.parts).join(', ')}]),\n    },\n`;
}
out += `  ],\n  beside: [${pairs.map(([a, b]) => `[${h2(a)}, ${h2(b)}]`).join(', ')}],\n};\n`;
fs.writeFileSync('games/blackwyche/src/pictures.ts', out);
console.log(`games/blackwyche/src/pictures.ts: ${pictures.length} pictures, ${pictures.reduce((n, p) => n + p.pieces.length, 0)} pieces, ${pairs.length} pairs side by side`);
for (const p of pictures) {
  const count = (k: string) => p.pieces.filter((q) => q.kind === k).length;
  console.log(`  ${h2(p.id)}/${p.variant}: ${count('wall')} walls (${p.pieces.filter((q) => q.kind === 'wall').map((q) => q.kind === 'wall' ? q.depth : 0).join(', ')}), ${count('side')} side walls, ${count('thing')} things, ${p.parts.length / 3} cells in parts`);
}

// to look at: each picture drawn (deck colours), tinted by its pieces (walls blue, side walls green, things
// warm, each its own, the floor as drawn), and beside it each pixel's depth (near light, far dark)
if (outDir) {
  fs.mkdirSync(outDir, { recursive: true });
  for (const [k, p] of pictures.entries()) {
    const set = sources[k].charset, W = 320, H = 136, rgb = new Float32Array(W * 2 * H * 3), pix = pixelPieces(p);
    for (let y = 0; y < H; y++) for (let x = 0; x < W; x++) {
      const code = p.codes[(y >> 3) * 40 + (x >> 3)], v = (set[code * 8 + (y & 7)] >> (6 - (x & 6))) & 3;
      const c = C64_PALETTE[[0, 8, 9, 7][v]], piece = p.pieces[pix[y * W + x]], id = pix[y * W + x];
      const tint = piece.kind === 'floor' ? [1, 1, 1] : piece.kind === 'wall' ? [0.55, 0.7, 1.3] : piece.kind === 'side' ? [0.6, 1.3, 0.6] : [1.3, 0.5 + ((id * 37) % 7) / 10, 0.4 + ((id * 53) % 5) / 8];
      const o = (y * W * 2 + x) * 3;
      rgb[o] = Math.min(1, ((c >> 16) / 255 + 0.15) * tint[0]); rgb[o + 1] = Math.min(1, (((c >> 8) & 255) / 255 + 0.15) * tint[1]); rgb[o + 2] = Math.min(1, ((c & 255) / 255 + 0.15) * tint[2]);
      const z = piece.kind === 'floor' ? 136 - y - 0.5 - piece.height : piece.kind === 'side' ? piece.slope * (x + 0.5) - piece.at : piece.depth;
      const d = Math.max(0, Math.min(1, 1 - z / 120)), q = (y * W * 2 + W + x) * 3;
      rgb[q] = d; rgb[q + 1] = d * (piece.kind === 'thing' ? 0.6 : 1); rgb[q + 2] = d * (piece.kind === 'floor' ? 0.6 : 1);
    }
    rgbPng(`${outDir}/${p.id.toString(16)}-${p.variant}.png`, rgb, W * 2, H, 2);
  }
}
