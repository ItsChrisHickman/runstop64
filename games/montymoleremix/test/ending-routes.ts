/**
 * Makes src/ending-routes.ts: the route of each place of the reward show (src/ending.ts), found by the passability bot (test/bot.ts) on a game put at the
 * place's start (`sceneGame`, the very game the show plays): every piece of the room's coal, the tool where a piece needs it, then the way on to the next
 * room; a stick a frame, as text (shared/ending/pilot.ts). The next place starts where the way on put him.
 *
 *   nice -n 15 node tools/test.mjs games/montymoleremix/test/ending-routes.ts
 *
 * Not a check (it writes a file): the routes are played again, as the show plays them, by test/reward.ts.
 */
import fs from 'node:fs';
import { piecesOfRoom } from '../../montymole/src/coal-rules';
import { isMove, routeText, type Move } from '../../shared/ending/pilot';
import type { MontyInput } from '../../shared/monty/body';
import { ROOMS } from '../../montymole/src/data/rooms-data';
import { DIRECTIONS, bitOf, factsOf, find, RoomMap, sticksOf, type Direction } from './bot';
import { type Play } from './harness';
import { SCENE_ROOMS, sceneGame } from '../src/ending';
import { HOME_COL, HOME_ROW, ROOM0_START_X2, ROOM0_START_Y, type RemixGame } from '../src/game';

/** A stick as the route's text has it. */
function moveOf(s: MontyInput): Move {
  const dir = s.up && s.left ? '^<' : s.up && s.right ? '^>' : s.down && s.left ? 'v<' : s.down && s.right ? 'v>' : s.left ? '<' : s.right ? '>' : s.up ? '^' : s.down ? 'v' : '.';
  const token = s.fire ? (dir === '.' ? 'J' : `J${dir}`) : dir;
  if (!isMove(token)) throw new Error(`no such move: ${token}`);
  return token;
}

/** The direction of the way on from a room: the one that leads to the next room. */
function wayOn(g: RemixGame, room: number): Direction {
  const next = room + 1;
  const to = { up: [-1, 0], down: [1, 0], left: [0, -1], right: [0, 1] } as const;
  const d = DIRECTIONS.find((dir) => g.roomAt(HOME_ROW + to[dir][0], HOME_COL + to[dir][1]) === next);
  if (d === undefined) throw new Error(`room ${room} has no way on to ${next}`);
  return d;
}

let spot = { x2: ROOM0_START_X2, y: ROOM0_START_Y, facing: 0x01 };
let taken = 0;
const lines: string[] = [];
for (const room of SCENE_ROOMS) {
  const start = { ...spot, taken };
  let cur: Play = { g: sceneGame(room, start), col: 0 };
  const map = new RoomMap(factsOf(cur.g));
  map.addStart(cur.g);
  map.explore();
  const facts = map.facts;
  const direction = wayOn(cur.g, room);
  /**
   * The pieces in an order that can be had, then the way on: the nearest first by the map, and where the rest cannot be had from there (a drop that is
   * not climbed back) the next nearest first instead.
   */
  const plan = (from: Play, left: readonly number[]): { sticks: MontyInput[]; end: Play } | null => {
    if (left.length === 0) {
      const found = find(from, map, { kind: 'exit', direction }, 40000);
      return 'play' in found ? { sticks: sticksOf(from, found.steps), end: found.play } : null;
    }
    const distance = (id: number): number => map.from(from.g, bitOf(facts, { kind: 'piece', id })) ?? Infinity;
    for (const id of [...left].sort((a, b) => distance(a) - distance(b))) {
      const found = find(from, map, { kind: 'piece', id }, 20000);
      if (!('play' in found)) continue;
      const rest = plan(found.play, left.filter((k) => found.play.g.coal.isThere(k)));
      if (rest !== null) return { sticks: [...sticksOf(from, found.steps), ...rest.sticks], end: rest.end };
    }
    return null;
  };
  const goals = piecesOfRoom(room);
  const done = plan(cur, goals.filter((id) => cur.g.coal.isThere(id)));
  if (done === null) throw new Error(`room ${room}: no way to every piece and on`);
  const sticks = done.sticks;
  cur = done.end;
  const route = routeText(sticks.map(moveOf));
  lines.push(`  ${room}: { x2: ${start.x2}, y: ${start.y}, facing: ${start.facing}, taken: ${start.taken}, route: '${route}' },`);
  console.log(`room ${room}: ${sticks.length} frames, ${goals.length} pieces; on to room ${cur.g.roomId} at x2 ${cur.g.x2} y ${cur.g.y}`);
  spot = { x2: cur.g.x2, y: cur.g.y, facing: cur.g.facing };
  taken += goals.length;
}
fs.writeFileSync('games/montymoleremix/src/ending-routes.ts', `// Generated by games/montymoleremix/test/ending-routes.ts: do not edit by hand.
/** Where a scene of the reward show begins: the place Monty comes into the room, and how many pieces of coal are taken elsewhere (so that a gate's room opens its gate). */
export interface SceneStart { readonly x2: number; readonly y: number; readonly facing: number; readonly taken: number }
/** A room's route for the show: its start, and the stick of every frame as the shared pilot reads them (\`shared/ending/pilot.ts\`: a stick, a run at a time). */
export interface SceneRoute extends SceneStart { readonly route: string }
export const ROUTES: Readonly<Record<number, SceneRoute>> = {
${lines.join('\n')}
};
`);
console.log(`wrote src/ending-routes.ts (${ROOMS.length} rooms in the game, ${SCENE_ROOMS.length} places)`);
