/**
 * Builds games/entombed/src/pictures.ts: Entombed's rooms as pieces (c64kit's pendragon/room.ts),
 * decoded from the game's own room pictures by games/shared/pendragon/decode.ts (re/README.md, "The
 * rooms as pieces"):
 *
 * - Entombed is the same engine as Blackwyche's: each room is a picture of 40 × 17 characters at a page
 *   of its own (the 16 rows of the room and, in the last, the floor's front edge), laid out 768 bytes
 *   apart from $7000, copied to the screen's rows 4-20;
 * - the corridors' pictures ($70, $73, $76, $79, $7C, $7F, $82, $85, $88) are what the maze tables
 *   hold (a byte a cell: the page of the picture drawn there; $7C and $7F the ends: a wall where the
 *   corridor stops), the picture of the cell he's at scrolling along into the next cell's as he walks:
 *   two pictures side by side (`beside`: the neighbours in the maze, either way round);
 * - the chambers' ($8B, $8E, $91, $9A, $9D, $A0, $A3, $A6, $A9, $AC, $AF, $B2, $B5: one each, or one
 *   for the twins: 2, 10 and 23 are $8E's, 3, 5, 7, 12, 15 and 17 $91's, 4 and 21 $A0's, 6, 18 and 22 $AF's,
 *   13 and 24 $A6's, 19 and 20 $B2's) each wider chamber scrolling a few columns either way (the
 *   rest of the screen the engine fills with what's beyond the room's end);
 * - all in the character set at $3800.
 *
 *   nice -n 15 node tools/test.mjs games/entombed/re/pictures.ts [out-dir: each picture's pieces as PNGs]
 */
import fs from 'node:fs';
import { unpackState } from '../../../packages/c64kit/src/c64/machine';
import { pixelPieces, type RoomPicture } from '../../../packages/c64kit/src/pendragon/room';
import { decodePictures, type PictureSource } from '../../shared/pendragon/decode';
import { rgbPng } from '../../../tools/probe/render';
import { C64_PALETTE } from '../../../packages/c64kit/src/palette';
import { maze } from '../src/map';
import { entombedRules } from '../src/hd';

const ram = unpackState(new Uint8Array(fs.readFileSync('games/entombed/assets/entombed-title.state'))).ram;
const outDir = process.argv[2];
const COLS = 40, ROWS = 17;
const CORRIDORS = [0x70, 0x73, 0x76, 0x79, 0x7c, 0x7f, 0x82, 0x85, 0x88];
const CHAMBERS = [0x8b, 0x8e, 0x91, 0x9a, 0x9d, 0xa0, 0xa3, 0xa6, 0xa9, 0xac, 0xaf, 0xb2, 0xb5];
const charset = ram.slice(0x3800, 0x4000);
/** The front edge: the floor's last row is row 19 (index 15 of the 17: rows 4-20), under it its face. */
const FRONT = 15;
/** The wider chambers scroll the screen along their picture up to 9 columns (chamber 1; others 3 or 2), left or right. */
const OVERHANG = 9;
const sources: PictureSource[] = [...CORRIDORS, ...CHAMBERS].map((id) => ({
  id, variant: 0, cols: COLS, rows: ROWS, codes: ram.slice(id * 256, id * 256 + COLS * ROWS), charset, set: 'tomb', front: FRONT,
}));
const pictures = decodePictures(sources, entombedRules);

// side by side: the corridors' neighbouring cells, either way round
const beside = new Set<string>();
for (let floor = 1; floor <= 7; floor++) {
  const m = maze(ram, floor);
  for (let y = 0; y < m.F.h; y++) for (let x = 0; x < m.F.w; x++) {
    for (const [a, b] of [[m.row(x, y), m.row(x + 1, y)], [m.col(x, y), m.col(x, y + 1)]]) {
      if (a && b && CORRIDORS.includes(a) && CORRIDORS.includes(b)) { beside.add(`${a},${b}`); beside.add(`${b},${a}`); }
    }
  }
}
const pairs = [...beside].map((s) => s.split(',').map(Number)).sort((a, b) => a[0] - b[0] || a[1] - b[1]);

const hex = (b: Uint8Array) => Buffer.from(b).toString('hex');
const h2 = (n: number) => `0x${n.toString(16).padStart(2, '0')}`;
const pieceText = (p: RoomPicture['pieces'][number]) => p.kind === 'floor' ? `{ kind: 'floor', height: ${p.height} }` : p.kind === 'side' ? `{ kind: 'side', slope: ${p.slope}, at: ${p.at} }` : `{ kind: '${p.kind}', depth: ${p.depth} }`;
let out = `// Generated by games/entombed/re/pictures.ts from the game's own room pictures: do not edit by hand.
import { hexBytes, type RoomPictures } from 'c64kit';

/**
 * Entombed's rooms as pieces (c64kit's pendragon/room.ts): each picture the game draws a room from (its
 * page: the corridors' $70-$88, the chambers' $8B-$B5), decoded into where each piece of it stands; and
 * which pictures stand side by side (the corridors' neighbouring cells).
 */
export const PICTURES: RoomPictures = {
  pictures: [
`;
for (const p of pictures) {
  out += `    {\n      id: ${h2(p.id)}, variant: ${p.variant}, cols: ${p.cols}, rows: ${p.rows},\n`;
  out += `      codes: hexBytes('${hex(p.codes)}'),\n`;
  out += `      cells: hexBytes('${hex(p.cells)}'),\n`;
  out += `      pieces: [\n${p.pieces.map((q) => `        ${pieceText(q)},`).join('\n')}\n      ],\n`;
  out += `      parts: Uint32Array.from([${Array.from(p.parts).join(', ')}]),\n    },\n`;
}
out += `  ],\n  beside: [${pairs.map(([a, b]) => `[${h2(a)}, ${h2(b)}]`).join(', ')}],\n  overhang: ${OVERHANG},\n};\n`;
fs.writeFileSync('games/entombed/src/pictures.ts', out);
console.log(`games/entombed/src/pictures.ts: ${pictures.length} pictures, ${pictures.reduce((n, p) => n + p.pieces.length, 0)} pieces, ${pairs.length} pairs side by side`);
for (const p of pictures) {
  const count = (k: string) => p.pieces.filter((q) => q.kind === k).length;
  console.log(`  ${h2(p.id)}: ${count('floor')} floors (${p.pieces.filter((q) => q.kind === 'floor').map((q) => q.kind === 'floor' ? q.height : 0).join(', ')}), ${count('wall')} walls (${p.pieces.filter((q) => q.kind === 'wall').map((q) => q.kind === 'wall' ? q.depth : 0).join(', ')}), ${count('side')} side walls, ${count('thing')} things, ${p.parts.length / 3} cells in parts`);
}

// to look at: each picture drawn, tinted by its pieces (walls blue, side walls green, things warm, each its
// own, the floor as drawn), and under it each pixel's depth (near light, far dark)
if (outDir) {
  fs.mkdirSync(outDir, { recursive: true });
  for (const p of pictures) {
    const W = p.cols * 8, H = p.rows * 8, rgb = new Float32Array(W * H * 2 * 3), pix = pixelPieces(p), bottom = H;
    for (let y = 0; y < H; y++) for (let x = 0; x < W; x++) {
      const code = p.codes[(y >> 3) * p.cols + (x >> 3)], v = (charset[code * 8 + (y & 7)] >> (6 - (x & 6))) & 3;
      const c = C64_PALETTE[[0, 8, 9, 7][v]], piece = p.pieces[pix[y * W + x]], id = pix[y * W + x];
      const tint = piece.kind === 'floor' ? [1, 1, 1] : piece.kind === 'wall' ? [0.55, 0.7, 1.3] : piece.kind === 'side' ? [0.6, 1.3, 0.6] : [1.3, 0.5 + ((id * 37) % 7) / 10, 0.4 + ((id * 53) % 5) / 8];
      const o = (y * W + x) * 3;
      rgb[o] = Math.min(1, ((c >> 16) / 255 + 0.15) * tint[0]); rgb[o + 1] = Math.min(1, (((c >> 8) & 255) / 255 + 0.15) * tint[1]); rgb[o + 2] = Math.min(1, ((c & 255) / 255 + 0.15) * tint[2]);
      const z = piece.kind === 'floor' ? bottom - y - 0.5 - piece.height : piece.kind === 'side' ? piece.slope * (x + 0.5) - piece.at : piece.depth;
      const d = Math.max(0, Math.min(1, 1 - z / 120)), q = ((H + y) * W + x) * 3;
      rgb[q] = d; rgb[q + 1] = d * (piece.kind === 'thing' ? 0.6 : 1); rgb[q + 2] = d * (piece.kind === 'floor' ? 0.6 : 1);
    }
    rgbPng(`${outDir}/${p.id.toString(16)}.png`, rgb, W, H * 2, 2);
  }
}
