/**
 * The hints table (src/hints.ts) from the activators (activators.ts) as done by playing
 * (solve.ts, one JSON per chamber in re/hints/solved): for each chamber, each step's spot (where
 * Pendragon was when he did it, the middle of his sprite on the unscrolled screen), the byte
 * and value that mark it done, and what it needs (its `when`, and the global flags the chamber
 * was solved with).
 *
 *   npx tsx games/entombed/re/hints/gen.ts > games/entombed/src/hints.ts
 */
import fs from 'node:fs';
import { ACTIVATORS } from './activators';
import { onScreen } from './play';
import { readSolved } from './solved';

const dir = new URL('./solved/', import.meta.url);
const out: Record<number, { spots: [number, number][]; until: [number, number]; when?: [number, number][]; sprite?: number; seen?: boolean }[]> = {};
for (const f of fs.readdirSync(dir).filter((n) => /^chamber-\d+\.json$/.test(n)).sort()) {
  const j = readSolved(new URL(f, dir));
  const spec = ACTIVATORS[j.chamber];
  if (!spec) continue;
  const hints = [];
  for (const st of spec.steps) {
    const done = j.steps.find((s) => s.name === st.name);
    if (!done) continue; // (not done by playing: no hint)
    const when: [number, number][] = [...Object.entries(spec.given ?? {}).map(([a, v]): [number, number] => [Number(a), v]), ...(st.when ?? [])];
    const spot: [number, number] = st.sprite ? [st.sprite[1], st.sprite[2]] : onScreen({ x: done.at[0], y: done.at[1] });
    hints.push({ spots: [spot], until: st.until, ...(when.length ? { when } : {}), ...(st.sprite ? { sprite: st.sprite[0] } : {}), ...(st.seen ? { seen: true } : {}) });
  }
  if (hints.length) out[j.chamber] = hints;
}
const hex = (n: number) => `0x${n.toString(16)}`;
const pair = ([a, v]: [number, number]) => `[${hex(a)}, ${v > 9 ? hex(v) : v}]`;
console.log(`/**
 * Where something can be done in Entombed's chambers, for the hints assist (see hint-spots.ts):
 * read from each chamber's code and done by playing it automatically (re/hints, see
 * re/README.md), not placed by hand. For each chamber ($321C): places on the unscrolled screen
 * (or on a moving sprite, \`sprite\`), shown until a byte has its done value (\`until\`) and while
 * what it needs holds (\`when\`).
 * Generated by re/hints/gen.ts.
 */
export interface Hint { spots: [number, number][]; until: [number, number]; when?: [number, number][]; sprite?: number; seen?: boolean }
export const HINTS: Record<number, Hint[]> = {
${Object.entries(out).map(([n, hs]) => `  ${n}: [\n${hs.map((h) => `    { spots: [${h.spots.map(([x, y]) => `[${x}, ${y}]`).join(', ')}], until: ${pair(h.until)}${h.when ? `, when: [${h.when.map(pair).join(', ')}]` : ''}${h.sprite !== undefined ? `, sprite: ${h.sprite}` : ''}${h.seen ? ', seen: true' : ''} },`).join('\n')}\n  ],`).join('\n')}
};`);
