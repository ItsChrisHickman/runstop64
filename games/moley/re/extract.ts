/**
 * Writes the rebuild's data modules (games/moley/src/data/) from the original: the tape's code block for the maps, tiles,
 * sprites, picture, panel and texts; the 48K ROM for the glyphs the game prints; the game in play for the beeper effects.
 * The output is committed (it is the data, not the program: no code of the original, no tape, no ROM).
 *
 *   nice -n 15 node tools/test.mjs games/moley/re/extract.ts [tape] [rom] [play.state]
 */
import fs from 'node:fs';
import { readRom } from '../../../tools/zx/boot';
import { bytesOf, imageFromTape, printedCharacters, recordEffects, romGlyph, SPANS, type Span } from './original';

const [tapeFile = 'games/moley/build/moley.tap', romFile = 'games/moley/build/48.rom', stateFile = 'games/moley/build/play.state'] = process.argv.slice(2);
const image = imageFromTape(new Uint8Array(fs.readFileSync(tapeFile)));
const rom = readRom(romFile);
const OUT = 'games/moley/src/data';

const hex = (b: Uint8Array) => Array.from(b, (v) => v.toString(16).padStart(2, '0')).join('');
const addr = (n: number) => `$${n.toString(16).toUpperCase()}`;

function constant(name: string, span: Span): string {
  return `/** ${span.name} (${addr(span.at)}-${addr(span.at + span.length - 1)}, ${span.length} bytes). */\nexport const ${name}: string =\n  '${hex(bytesOf(image, span))}';\n`;
}
function text(name: string, span: Span): string {
  const t = String.fromCharCode(...bytesOf(image, span));
  return `/** ${span.name} (${addr(span.at)}). */\nexport const ${name}: string = ${JSON.stringify(t)};\n`;
}
const head = (what: string) => `// Generated by games/moley/re/extract.ts from the original (${what}): do not edit.\n// Bytes as hex strings; src/data.ts turns them into typed tables.\n\n`;

fs.mkdirSync(OUT, { recursive: true });

fs.writeFileSync(`${OUT}/rooms-data.ts`, head('the tape\'s code block')
  + constant('MAPS_HEX', SPANS.maps) + '\n' + constant('ATTRS_HEX', SPANS.attrs) + '\n'
  + constant('TILES_HEX', SPANS.tiles) + '\n' + constant('ENDING_TILES_HEX', SPANS.endingTiles));

fs.writeFileSync(`${OUT}/graphics-data.ts`, head('the tape\'s code block')
  + constant('SPRITES_HEX', SPANS.sprites) + '\n' + constant('GAUGE_HEX', SPANS.gauge) + '\n'
  + constant('PANEL_BITMAP_HEX', SPANS.panelBitmap) + '\n' + constant('PANEL_ATTRS_HEX', SPANS.panelAttrs) + '\n'
  + constant('CREDITS_HEX', SPANS.credits));

fs.writeFileSync(`${OUT}/tables-data.ts`, head('the tape\'s code block')
  + constant('JUMP_STEPS_HEX', SPANS.jumpTable) + '\n' + constant('JUMP_FRAMES_HEX', SPANS.jumpFrames));

const chars = printedCharacters(image);
fs.writeFileSync(`${OUT}/texts-data.ts`, head('the tape\'s code block and the 48K ROM')
  + text('CREDITS_TEXT', SPANS.creditsText) + '\n' + text('ENDING_TEXT', SPANS.endingText) + '\n' + text('GAME_OVER_TEXT', SPANS.gameOverText) + '\n'
  + `/** The ROM glyphs the game prints ($3C00 + character * 8): the characters of its three texts, the numerals and the space. 8 bytes each. */\n`
  + `export const GLYPHS: readonly { readonly char: number; readonly hex: string }[] = [\n`
  + chars.map((c) => `  { char: ${c}, hex: '${hex(romGlyph(rom, c))}' },`).join('\n') + '\n];\n');

const effects = recordEffects(rom, new Uint8Array(fs.readFileSync(stateFile)));
fs.writeFileSync(`${OUT}/sounds-data.ts`, head('the game in play on the headless Spectrum')
  + `/** The beeper effects the game calls ($A017, A = id; 4 and 6 are never called), as the speaker did them: T-states before the first toggle, the T-states between toggles (each flips the speaker), and from the last toggle to the end. Effects 1 and 3 read the ROM as their noise. */\n`
  + `export const EFFECTS: readonly { readonly id: number; readonly lead: number; readonly gaps: readonly number[]; readonly tail: number }[] = [\n`
  + effects.map((e) => `  { id: ${e.id}, lead: ${e.lead}, tail: ${e.tail}, gaps: [${e.gaps.join(',')}] },`).join('\n') + '\n];\n');

console.log(`wrote ${OUT}: ${chars.length} glyphs, ${effects.map((e) => `effect ${e.id}: ${e.gaps.length + 1} toggles`).join(', ')}`);
