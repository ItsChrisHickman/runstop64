/**
 * The routes for the ending, found by playing (src/ending.ts uses them; src/ending-routes.ts is what this writes).
 *
 * For each screen: a new game on a fixed seed (`SteadyGame`: the same seed plays the same game, and a plan tried on a copy is what the game then does) put at the screen's start the way the
 * pause map's travel does (`Game.travel`), and the test suite's own player (test/players.ts: the goals of each screen, looked for by a search on
 * copies of the game, test/bot.ts) playing it, pass by pass, until the screen is left by its way out (or, in the last, the ending comes).
 * The keys of each pass are written down, run by run. A seed in which a life is lost is not kept (the next is tried): the show's Monty
 * never dies. Playing them again in the show, on a game of the same seed, is the same game pass for pass.
 *
 *   nice -n 15 node tools/test.mjs games/moley/re/ending/route.ts
 */
import fs from 'node:fs';
import { START_LIVES } from '../../src/game';
import { SteadyGame } from '../../src/steady';
import { ENDING_ROOM } from '../../src/data';
import { MOVES, survives } from '../../test/bot';
import { Player } from '../../test/players';

/** The most passes a screen may take (the original's passes are 25 a second: five minutes). */
const LIMIT = 7500;

/** One run: the keys held, for how many passes. */
type Run = readonly [number, number];

let why = '';
/**
 * One try at a screen on seed `seed`. The player is deterministic and some screens' hazards catch it every time, so each try has it
 * now and then (`noise`) press another key that it can live through for a while instead of the one it chose; the tries differ.
 */
function play(room: number, seed: number, noise: number): { runs: Run[]; passes: number; score: number } | null {
  const game = new SteadyGame(seed);
  if (room > 0) game.travel(room);
  const player = new Player(new SteadyGame(seed));
  const copy = new SteadyGame(seed);
  let state = Math.imul(seed, 2654435761) >>> 0;
  const random = () => { state = (Math.imul(state, 1664525) + 1013904223) >>> 0; return state / 4294967296; };
  const keys: number[] = [];
  for (let pass = 0; pass < LIMIT; pass++) {
    let k = player.keys(game);
    if (noise > 0 && random() < noise) {
      const snap = game.snapshot();
      const options = MOVES.filter((m) => survives(copy, snap, [m, ...Array<number>(12).fill(0)], true));
      if (options.length > 0) k = options[Math.floor(random() * options.length)];
    }
    keys.push(k);
    const outcome = game.pass(k);
    if (game.lives < START_LIVES) { why = `a life lost at pass ${pass} (room ${game.room})`; return null; }
    if (outcome === 'ended' || game.room !== room) {
      const runs: [number, number][] = [];
      for (const key of keys) { const last = runs[runs.length - 1]; if (last && last[0] === key) last[1]++; else runs.push([key, 1]); }
      return { runs, passes: keys.length, score: game.score };
    }
  }
  why = `no way out in ${LIMIT} passes (room ${game.room}, items left ${game.itemsLeft})`;
  return null;
}

const found: Record<number, { seed: number; runs: Run[] }> = {};
for (let room = 0; room < ENDING_ROOM; room++) {
  for (let seed = 1; seed <= Number(process.env.TRIES ?? 40) && found[room] === undefined; seed++) {
    const t0 = performance.now();
    const r = play(room, seed, seed === 1 ? 0 : 0.03);
    console.log(`room ${room} seed ${seed}: ${r ? `${r.passes} passes (${(r.passes / 25).toFixed(0)} s), score ${r.score}, ${r.runs.length} runs` : why} in ${((performance.now() - t0) / 1000).toFixed(0)}s`);
    if (r) found[room] = { seed, runs: r.runs };
  }
}
const body = Object.entries(found).map(([room, w]) => `  ${room}: { seed: ${w.seed}, runs: [${w.runs.map(([k, n]) => `[${k}, ${n}]`).join(', ')}] },`).join('\n');
fs.writeFileSync('games/moley/src/ending-routes.ts', `// Generated by games/moley/re/ending/route.ts: do not edit by hand.
/** A screen's route for the ending: the seed of the game it was played on, and the keys of each pass (the bits of \`Key\`), run by run: [keys, passes]. */
export interface Route { readonly seed: number; readonly runs: readonly (readonly [number, number])[] }
export const ROUTES: Record<number, Route> = {
${body}
};
`);
