/**
 * Writes the 128K music as data (games/moley/src/data/music-data.ts): the tape in the 128K model (re/music.ts explores it), the
 * register image after each 25 Hz step of the game's player for two whole passes of the tune (to prove it repeats exactly),
 * one pass of the steps delta-coded (c64kit's `packAyStream`) and written in base64. The output is committed: it is data recorded
 * from the original running, not its code, and the tape is not.
 *
 *   nice -n 15 node tools/test.mjs games/moley/re/record-music.ts [tape] [rom]
 */
import fs from 'node:fs';
import { packAyStream } from '../../../packages/c64kit/src/ay/tune';
import { readRom, readTape } from '../../../tools/zx/boot';
import { musicSteps, recordMusic } from './original';

const [tapeFile = 'games/moley/build/moley.tap', romFile = 'games/moley/build/48.rom'] = process.argv.slice(2);
const OUT = 'games/moley/src/data/music-data.ts';
/** Two passes of the tune (18,436 frames each, after the 142 the game takes to start it) and a few steps. */
const FRAMES_FOR_TWO_PASSES = 37_100;

const steps = musicSteps(recordMusic(readRom(romFile), readTape(tapeFile), FRAMES_FOR_TWO_PASSES));
const bytes = packAyStream(steps);
let binary = '';
for (const b of bytes) binary += String.fromCharCode(b);
const base64 = btoa(binary);
fs.writeFileSync(OUT, `// Generated by games/moley/re/record-music.ts from the original (the tape on the 128K model): do not edit.
// The AY registers after each step of the game's 25 Hz player for one whole pass of the tune, delta-coded
// (packages/c64kit/src/ay/tune.ts), as base64. src/music.ts decodes it.

/** The steps of one pass of the tune (the step at its end is held for two, as the original's is) and the bytes they take. */
export const MUSIC_STEPS = ${steps.length};
export const MUSIC_BYTES = ${bytes.length};
export const MUSIC_BASE64: string =
  '${base64}';
`);
console.log(`wrote ${OUT}: ${steps.length} steps in ${bytes.length} bytes (${base64.length} characters of base64)`);
