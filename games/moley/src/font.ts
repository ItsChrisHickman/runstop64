/** The characters the font has. */
export const FONT_CHARACTERS: string = Object.keys(ROWS).join('');

/** The font for our own text (a `BitmapFont` of the shared pause screen and panels). */
export function spectrumFont(): BitmapFont {
  const font = new BitmapFont();
  for (const [ch, rows] of Object.entries(ROWS)) font.glyphs.set(ch.charCodeAt(0), Uint8Array.from(rows));
  return font;
}
