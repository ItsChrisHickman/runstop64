/**
 * Extracts Auf Wiedersehen Monty's rooms and the tables that draw them from a snapshot of the
 * original at the start of play (games/awm/build/README.md), and writes them as a generated
 * TypeScript data module, games/awm/src/data/awm-data.ts, with the addresses they came from.
 *
 *   nice -n 15 node tools/test.mjs games/awm/re/rooms.ts games/awm/build/play.state [out.ts]
 *
 * Nothing here is a copy of the game's code: rooms (header and RLE bytes), the tile graphics,
 * the character set, the items' graphics, colours and places, the world's room grid and the
 * enemies' per-room tables, as the game keeps them.
 */
import fs from 'node:fs';
import { C64Machine, unpackState } from 'c64kit';
import { parseRoom, ROOM_COUNT } from '../src/room';

const [stateFile, outFile = 'games/awm/src/data/awm-data.ts'] = process.argv.slice(2);
if (!stateFile) throw new Error('usage: rooms.ts <play.state> [out.ts]');
const m = new C64Machine();
m.loadState(unpackState(new Uint8Array(fs.readFileSync(stateFile))));
const ram = m.ram;

const hex = (a: number, n: number) => Array.from(ram.subarray(a, a + n), (b) => b.toString(16).padStart(2, '0')).join('');
const word = (i: number) => ram[0x5a69 + i] | (ram[0x5ab9 + i] << 8);

/** The bytes a room takes in the game's data: to the next room's pointer; for the last, its RLE and the $00 after it. */
function spanOf(i: number): number {
  const p = word(i);
  if (i + 1 < ROOM_COUNT) return word(i + 1) - p;
  const end = p + 30 + parseRoom(ram.subarray(p, p + 0x400)).rle.length;
  return end - p + (ram[end] === 0 ? 1 : 0);
}

const rooms: string[] = [];
const odd: string[] = [];
let expect = 0x8700;
for (let i = 0; i < ROOM_COUNT; i++) {
  const p = word(i), n = spanOf(i);
  if (p !== expect) throw new Error(`room ${i} at $${p.toString(16)}, expected $${expect.toString(16)} (rooms are consecutive)`);
  const room = parseRoom(ram.subarray(p, p + n));
  if (room.extra.length !== 1 || room.extra[0] !== 0) odd.push(`${i}: ${room.extra.length} bytes after its cells`);
  rooms.push(hex(p, n));
  expect = p + n;
}
console.log('rooms whose data is not RLE + $00:', odd.join('; ') || 'none');
const sEnd = 0xbe06 + 30 + parseRoom(ram.subarray(0xbe06, 0xbe06 + 0x400)).rle.length;
const special = hex(0xbe06, sEnd + (ram[sEnd] === 0 ? 1 : 0) - 0xbe06);

const lines: string[] = [];
const out = (s: string) => lines.push(s);
const strArray = (name: string, doc: string, items: string[]) => {
  out(`/** ${doc} */`);
  out(`export const ${name}: readonly string[] = [`);
  for (const s of items) out(`  '${s}',`);
  out('];\n');
};
const str = (name: string, doc: string, s: string) => {
  out(`/** ${doc} */`);
  out(`export const ${name} = '${s}';\n`);
};
out('// Generated by games/awm/re/rooms.ts from the original running at the start of play: do not edit.');
out('// Bytes as hex strings; src/data.ts turns them into typed tables.\n');
strArray('ROOM_HEX', `The ${ROOM_COUNT} rooms, in room-number order (the game's pointer table at $5A69/$5AB9, from $8700): 30-byte header, RLE, $00.`, rooms);
str('SPECIAL_ROOM_HEX', 'Room $63, the picture the game draws before play ($BE06).', special);
str('TILE_GFX_HEX', 'Tile graphics, 8 bytes per tile name, names $00-$FF ($2A40).', hex(0x2a40, 0x800));
str('CHARSET_HEX', 'The character set ($3800, 256 characters) as it stands in play: characters 1-15 and 47-62 are the last room\'s tiles and items.', hex(0x3800, 0x800));
str('SPRITE_FRAMES_HEX', 'Sprite frames, 256 of 32 bytes ($0A40): 16 rows of 2 bytes, a 16 x 16 hires picture (the game copies a frame into a sprite\'s 3-byte rows, or mirrored, $66CA).', hex(0x0a40, 0x2000));
str('ARCS_HEX', 'Signed vertical steps of Monty\'s jumps and falls, per logic step ($4F8A-$5004; the jump of state 1 reads 24 of them from $4FB5, and ends level).', hex(0x4f8a, 0x7b));
str('RANDOM_HEX', 'The 256 numbers the game\'s random generator ($51F7) reads, in order of a step of $29 through them plus a carry ($3300).', hex(0x3300, 256));
str('ITEM_GFX_HEX', 'Item graphics, 32 types of 32 bytes ($2640).', hex(0x2640, 0x400));
str('ITEM_COLOURS_HEX', 'Item colours, 4 bytes a type ($597C).', hex(0x597c, 0x80));
str('ITEM_LIST_HEX', 'The item list, 236 of 3 bytes ($6D7B): room (bit 7 set once collected), type | cell low bits << 5, cell high bits.', hex(0x6d7b, 236 * 3));
str('WORLD_GRID_HEX', 'The world: 16 columns of rooms, row by row ($45AD, 240 bytes): a room number, or $63 for none. A room\'s neighbours are at the grid index -1, +1, -16, +16.', hex(0x45ad, 240));
str('ENEMY_ROOM_HEX', 'The enemies of each room, 16 bytes a room ($703F + 16 x room): four enemies of 4 bytes.', hex(0x703f, 16 * ROOM_COUNT));
str('ENEMY_COLOURS_HEX', 'The enemies\' colours, 4 bytes a room ($3400 + 4 x room).', hex(0x3400, 4 * ROOM_COUNT));

// ---- what the picture draws (stage 4) ----------------------------------------------------------

/** A text as the game keeps it: ASCII, the last character with bit 7 set. */
function text(at: number): string {
  let s = '';
  for (let i = 0; i < 40; i++) {
    const b = ram[at + i] ?? 0;
    s += String.fromCharCode(b & 0x7f);
    if (b & 0x80) return s;
  }
  throw new Error(`text at $${at.toString(16)} does not end`);
}
const banners: string[] = [];
for (let room = 0; room < ROOM_COUNT; room++) {
  // ($65A3: four bytes a room from $F52F: the country's text, then the place's, as pointers)
  const at = 0xf52f + 4 * room;
  banners.push(`${text((ram[at] ?? 0) | ((ram[at + 1] ?? 0) << 8))}|${text((ram[at + 2] ?? 0) | ((ram[at + 3] ?? 0) << 8))}`);
}
strArray('BANNERS', 'What each room\'s banner says ($65A3, the table at $F52F): the country, then the place, separated by |.', banners);
str('HUD_BAR', 'The line the banner is drawn over ($863A): the chain, in green.', text(0x863a));
str('HUD_SCORE', 'The label of the score ($865A).', text(0x865a));
str('HUD_MONEY', 'The label of the money ($8660).', text(0x8660));
str('HUD_HIGH', 'The label of the high score ($8666).', text(0x8666));
str('PROGRESS_HEX', 'The progress picture ($6656): the characters of its three parts (20, 20 and 18) then their colours ($6690).', hex(0x6656, 58) + hex(0x6690, 58));
str('DECOR_HEX', 'The three sprite pictures of the side columns ($3240, $3280, $32C0: pointers $C9, $CA, $CB), 64 bytes each.', hex(0x3240, 0xc0));
// ---- the flight (the shop's key, $758F: re/README.md) -------------------------------------------

str('FLIGHT_HEX', 'The flight\'s memory, which the VIC reads from the bank at $C000 ($D000-$DFCF, under the I/O area): the character set ($D000, 256 characters), the pictures of the sprites (64 bytes each, pointer $60 at $D800: the player\'s planes, the enemy\'s, an explosion, the clouds) and the sky\'s map ($DD00, 18 rows of 40 characters).', hex(0xd000, 0xfd0));
str('FLIGHT_TO_HEX', 'Where a plane flies to ($753F, a byte a room): the room it comes down in, $FF for a room with none.', hex(0x753f, ROOM_COUNT));
str('FLIGHT_PATHS_HEX', 'The enemy plane\'s four paths ($7709): a table of four pointers, then each path: where it starts (x, y) and segments of (kind, speed, count) up to a kind of 0.', hex(0x7709, 0x77e3 - 0x7709));
str('SLOT_COLOURS_HEX', 'The colours of the carried item boxes and the room\'s item slots as they stand at the start ($6D6B, 4 a slot).', hex(0x6d6b, 16));
fs.writeFileSync(outFile, lines.join('\n'));
console.log(`wrote ${outFile}: ${rooms.length} rooms (${rooms.reduce((a, r) => a + r.length / 2, 0)} bytes), special room ${special.length / 2} bytes`);
