/**
 * Extracts what the title and the closing screen draw from, as a generated TypeScript module
 * (games/awm/src/data/title-data.ts): the menu's font, the big letters (the scroller's and GAME OVER's sprite
 * pictures), the scroller's text and its sprites' start positions, as the game keeps them.
 *
 *   nice -n 15 node tools/test.mjs games/awm/re/title-data.ts games/awm/build/title.ram [out.ts]
 *
 * `title.ram` is the 64K of RAM when the program first reaches $406E, the title's set-up (games/awm/build/README.md):
 * the scroller's variables are then as the program file leaves them.
 */
import fs from 'node:fs';

const [ramFile, outFile = 'games/awm/src/data/title-data.ts'] = process.argv.slice(2);
if (!ramFile) throw new Error('usage: title-data.ts <title.ram> [out.ts]');
const ram = new Uint8Array(fs.readFileSync(ramFile));
const hex = (a: number, n: number): string => Array.from(ram.subarray(a, a + n), (b) => b.toString(16).padStart(2, '0')).join('');

/** The scroller's text ($44B3, screen-code-like letters, a $00 ends it and it starts again). */
let end = 0x44b3;
while (ram[end] !== 0) end++;
const lines: string[] = [];
const out = (s: string): void => { lines.push(s); };
const str = (name: string, doc: string, s: string): void => { out(`/** ${doc} */`); out(`export const ${name} = '${s}';\n`); };
out('// Generated by games/awm/re/title-data.ts from the original at the start of its title: do not edit.');
out('// Bytes as hex strings; src/title.ts and src/closing.ts turn them into what they draw.\n');
str('TITLE_FONT_HEX', 'The menu\'s lettering ($3C00): 8 bytes a character from the space ($20) to $5F.', hex(0x3c00, 64 * 8));
str('BIG_LETTERS_HEX', 'The big letters: sprite pictures of the characters $3E-$5A (64 bytes each; the sprite pointer is the character + $A4 in the VIC\'s bank 3, $F880-$FFBF), the scroller\'s alphabet and GAME OVER\'s.', hex(0xf880, 29 * 64));
str('SCROLL_TEXT_HEX', 'The scroller\'s text ($44B3) up to its $00: where it starts again.', hex(0x44b3, end - 0x44b3 + 1));
str('SCROLL_START_HEX', 'The scroller\'s variables as the program starts ($4457-$4477): the counter, then 8 words of x (the sprites 50 apart) and 8 words of y.', hex(0x4457, 0x21));
fs.writeFileSync(outFile, lines.join('\n'));
console.log(`wrote ${outFile}: text ${end - 0x44b3 + 1} bytes`);
