/**
 * Audit: the game's own item data, room by room. Each room is entered the way travel does it (the
 * way down from a copy of the start, so every item is still there) and the game's tables read once
 * its loader has run: $8106 the room's item count, $8108... one pair (colour RAM address low, high)
 * per item, the character cell it sits in ($D800 + row * 40 + column).
 *
 *   nice -n 15 node tools/test.mjs games/jsw2/re/items.ts
 *
 * Prints one line per room and the totals, and writes re/items.json (room -> item cells) and
 * src/itemcounts.ts (room -> how many items it holds, for the pause map, and where they sit, for the sparkles).
 */
import fs from 'node:fs';
import { unpackState } from '../../../packages/c64kit/src/c64/machine';
import { NativeHost } from '../../shared/native/host';
import { port } from '../src/native';
import { MANSION } from '../src/mansion';

const IDLE = 0x1f, FIRE = 0x1f & ~16;
const START: number[] = [...Array<number>(80).fill(IDLE), ...Array<number>(3).fill(FIRE), ...Array<number>(200).fill(IDLE)];
const title = new Uint8Array(fs.readFileSync('games/jsw2/assets/jsw2-title.state'));
const g0 = new NativeHost(port, unpackState(title));
const frame = (g: NativeHost, joy: number) => { g.m.joy1 = IDLE; g.m.joy2 = joy; g.tick(); g.m.ram[0x8096] = 0xff; };
let saved: ReturnType<NativeHost['save']> = null;
g0.onWait = () => { saved = g0.save(); };
for (const j of START) frame(g0, j);
const base = saved;
if (!base) throw new Error('no save');

const out: Record<number, { name: string; cells: [number, number][] }> = {};
let total = 0;
for (const n of Object.keys(MANSION).map(Number)) {
  const g = NativeHost.resume(port, base);
  g.m.ram[0x816c] = n; g.m.ram[0x8063] = 0xa2;
  for (let f = 0; f < 12 && g.m.ram[0x13] !== n; f++) frame(g, IDLE);
  for (let f = 0; f < 3; f++) frame(g, IDLE); // (its loader has run)
  const r = g.m.ram;
  if (r[0x13] !== n) { console.log(n, MANSION[n].name, 'NOT ENTERED', r[0x13]); continue; }
  const count = r[0x8106], cells: [number, number][] = [];
  for (let i = 0; i < count; i++) {
    const a = (r[0x8108 + 2 * i] | (r[0x8109 + 2 * i] << 8)) - 0xd800;
    cells.push([Math.floor(a / 40), a % 40]);
  }
  total += count;
  if (r[0x8173]) console.log('special', n, MANSION[n].name, 'type', r[0x8173], 'vec1e0', (r[0x1e0] | (r[0x1e1] << 8)).toString(16));
  out[n] = { name: MANSION[n].name, cells };
  console.log(String(n).padStart(3), String(count).padStart(2), MANSION[n].name, count ? JSON.stringify(cells) : '');
}
const withItems = Object.values(out).filter((o) => o.cells.length).length;
console.log(`rooms ${Object.keys(out).length}, rooms with items ${withItems}, items ${total}`);
fs.writeFileSync('games/jsw2/re/items.json', JSON.stringify(out) + '\n');

const counts = Object.entries(out).filter(([, o]) => o.cells.length).map(([n, o]) => `  ${n}: ${o.cells.length},`);
const cells = Object.entries(out).filter(([, o]) => o.cells.length).map(([n, o]) => `  ${n}: ${JSON.stringify(o.cells)},`);
fs.writeFileSync('games/jsw2/src/itemcounts.ts', `// Generated by games/jsw2/re/items.ts from the game's own room loader: do not edit by hand.
/** How many items each room holds (rooms with none are left out). */
export const ITEM_COUNTS: Record<number, number> = {
${counts.join('\n')}
};

/** Where each room's items sit: [row, column] of the character cell, in the order of the room's item bits (rooms with none are left out). */
export const ITEM_CELLS: Record<number, [number, number][]> = {
${cells.join('\n')}
};
`);
