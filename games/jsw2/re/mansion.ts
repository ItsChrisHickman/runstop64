/**
 * Builds games/jsw2/src/mansion.ts: every room of the mansion, its name and exits. (Where each
 * room is on the pause screen's map is laid out by hand: src/cells.ts.) The game's own room loader ($62C5) is run
 * for each room number (in $13) on a copy of the machine; it leaves the room's name at
 * ($73) and its exits (left, right, up, down; the room itself where there's none) in
 * $8169-$816C. The rooms are the ones reachable from the start (the Bathroom) through
 * exits, and from the places the game sends Willy to directly.
 *
 *   nice -n 15 node tools/test.mjs games/jsw2/re/mansion.ts
 */
import fs from 'node:fs';
import { C64, unpackState, type MachineState } from '../../../packages/c64kit/src/c64/machine';

const START = 0x20;
/**
 * Rooms Willy cannot walk into, which the map does not show until he has been in one, and whose exits are not drawn:
 * 136, The Beginning of the End, is only the bathroom's right exit, and the bathroom's right side is a solid wall from floor to ceiling
 * (the room drawn; 120 random walks of 3000 frames through the room reached x 326 at most, while a room with a way out on the right
 * lets Willy out at x 328, and left only through the drain); only the game's own end, which walks him there (put to bed, he sleepwalks
 * through 33, 63, 64 and the bathroom into 136), enters it.
 */
const UNENTERABLE = [136];
/** Rooms the game sends Willy to directly (its code stores them in $13). */
const SENT_TO = [0x6e, 0x79, 0x61];

const o = new C64();
o.loadState(unpackState(new Uint8Array(fs.readFileSync('games/jsw2/assets/jsw2-title.state'))));
// a play state: the original at the top of its main loop
const got: { play: MachineState | null } = { play: null }; // (taken by the step hook)
let passes = 0;
const step = o.cpu.step.bind(o.cpu);
o.cpu.step = () => { if (!got.play && o.cpu.pc === 0x4bae && ++passes > 30) got.play = o.saveState(); return step(); };
for (let f = 0; f < 400 && !got.play; f++) { o.joy2 = f >= 40 && f < 44 ? 0x0f : 0x1f; o.runFrame(); }
const play = got.play;
if (!play) throw new Error('the game never started');

const nameAt = (r: Uint8Array) => {
  const p = r[0x73] | (r[0x74] << 8);
  let s = '';
  for (let y = 1; y < 40; y++) {
    const c = r[p + y] & 0x7f;
    // screen codes: 1-26 lower case, $41-$5A upper case (shown in capitals here), $20-$3F as ASCII
    s += c >= 1 && c <= 26 ? String.fromCharCode(64 + c) : c >= 0x41 && c <= 0x5a ? String.fromCharCode(c) : c >= 0x20 && c <= 0x3f ? String.fromCharCode(c) : ' ';
    if (r[p + y] & 0x80) break;
  }
  return s.replace(/\s+/g, ' ').trim();
};
interface Room { name: string; exits: [number, number, number, number] }
/** A room as the game's own loader leaves it: the original's code run (from the play state) with Willy let fall through the way down into room `n`, as travel does. */
const load = (n: number): Room | null => {
  const m = new C64();
  m.loadState(play);
  m.ram[0x816c] = n; m.ram[0x8063] = 0xa2;
  m.ram[0x8096] = 0xff;
  let name = '';
  for (let f = 0; f < 80; f++) {
    m.joy2 = 0x1f;
    m.runFrame();
    m.ram[0x8096] = 0xff;
    if (m.ram[0x13] === n && f > 2) { name = nameAt(m.ram); if (f > 6) break; }
  }
  if (m.ram[0x13] !== n) return null;
  return { name, exits: [m.ram[0x8169], m.ram[0x816a], m.ram[0x816b], m.ram[0x816c]] };
};

const rooms = new Map<number, Room>();
const work = [START, ...SENT_TO];
for (let n = work.shift(); n !== undefined; n = work.shift()) {
  if (rooms.has(n)) continue;
  const r = load(n);
  if (!r) throw new Error(`room ${n} didn't load`);
  rooms.set(n, r);
  for (const e of r.exits) if (e !== n && !rooms.has(e)) work.push(e);
}

const lines = [...rooms].sort(([a], [b]) => a - b).map(([n, r]) => `  ${n}: { name: ${JSON.stringify(r.name)}, exits: [${r.exits.join(', ')}] },`);
const out = `// Generated by games/jsw2/re/mansion.ts from the game's own room data: do not edit by hand.
/** The mansion: each room's name and exits (left, right, up, down; itself where there's none). Where a room is on the map: cells.ts. */
export const MANSION: Record<number, { name: string; exits: [number, number, number, number] }> = {
${lines.join('\n')}
};
/** Rooms Willy cannot walk into (re/mansion.ts says how that is known; the game's own end puts him in 136): the map does not show them until he has been in one, and their exits are not drawn. */
export const UNENTERABLE: number[] = [${UNENTERABLE.join(', ')}];
`;
fs.writeFileSync('games/jsw2/src/mansion.ts', out);
console.log(`${rooms.size} rooms`);
