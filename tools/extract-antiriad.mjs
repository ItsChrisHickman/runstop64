#!/usr/bin/env node
// Extracts The Sacred Armour of Antiriad's data (rooms, blocks, character and
// sprite graphics, the status panel, tables, and the music driver with its
// tunes) from the game's memory as it stands when the game starts, once its
// loader has unpacked it: a 64K RAM dump made with tools/probe
// (games/antiriad/build/README.md shows how).
//
// Usage: node tools/extract-antiriad.mjs <ram.bin> [out.json]
//
// The game's own code ($8000-$AFC4) is left out: the port is a rewrite of it
// (games/antiriad/src). What's kept is laid out at its original addresses, so
// the port reads the same tables the original did. The one piece of code kept
// is the music driver ($AFC5-$B499), with the tunes: like the SID files the other
// games play, Richard Joseph's music is played by its own player code.

import fs from 'node:fs';
import crypto from 'node:crypto';

const [, , dump, out = 'games/antiriad/src/data/antiriad.json'] = process.argv;
if (!dump) {
  console.error('usage: node tools/extract-antiriad.mjs <ram.bin> [out.json]');
  process.exit(1);
}
const ram = fs.readFileSync(dump);
if (ram.length !== 0x10000) throw new Error(`${dump}: expected a 64K RAM dump, got ${ram.length} bytes`);
// The dump is checked: the game's entry ($8009) must be there, as the loader left it.
const md5 = crypto.createHash('md5').update(ram).digest('hex');
if (ram[0x8009] !== 0x78 || ram.toString('latin1', 0x8004, 0x8009) !== '\xc3\xc2\xcd80') throw new Error('not the game unpacked (no CBM80 entry at $8000)');

/** Memory regions, in address order: everything but the game's own code. */
const SECTIONS = [
  ['low', 0x0002, 0x0aff, 'zero page, stack and $0200-$0AFF as the loader leaves them: the game\'s variables (it sets most at start) and its small tables at $06A0-$07FF'],
  ['rooms', 0x0b00, 0x13ff, 'room layouts: 32 bytes per room, 4 rows of 8 blocks ($0B00 + room * 32)'],
  ['blocks', 0x1400, 0x23ff, 'blocks: 4x4 characters each, 16 bytes ($1400 + block * 16)'],
  ['charGraphics', 0x2400, 0x3bff, 'character definitions the rooms take their character sets from'],
  ['charColours', 0x3c00, 0x3eff, 'a colour for each of those characters (its low nibble also tells walls and platforms apart)'],
  ['graphicsSets', 0x3f00, 0x3fff, 'which characters each room takes (lists of ranges)'],
  ['vicBank', 0x4000, 0x7fff, 'the VIC-II\'s bank: screen, sprite shapes, the status panel\'s characters'],
  ['soundDriver', 0xafc5, 0xc1a9, 'the music and sound effect driver (6502 code) and its sequences'],
  ['tables', 0xc1aa, 0xcfff, 'messages, sprite movement scripts, item and enemy tables'],
  ['underIo', 0xd000, 0xdfff, 'RAM under the I/O area: the title screen\'s character set'],
  ['underKernal', 0xe000, 0xffff, 'RAM under the KERNAL: screen row addresses, room exits and colours, animation scripts, the panel, tune tables'],
];

const sections = {};
for (const [name, lo, hi, about] of SECTIONS) {
  sections[name] = { at: lo, about, data: ram.subarray(lo, hi + 1).toString('base64') };
}

// Decoded for the map and for reading: each room's exits (right, left, down, up; -1 = none).
const ROOMS = 0x45;
const exits = [];
for (let r = 0; r < ROOMS; r++) exits.push([0, 1, 2, 3].map((i) => (ram[0xf25a + r * 4 + i] & 0x80 ? -1 : ram[0xf25a + r * 4 + i])));

const json = {
  about: 'The Sacred Armour of Antiriad (Palace Software, 1986), Commodore 64: the game\'s data at its original addresses. Generated by tools/extract-antiriad.mjs; see games/antiriad/re/README.md.',
  source: { dumpMd5: md5 },
  rooms: ROOMS,
  exits,
  sections,
};
fs.mkdirSync(new URL('.', `file://${process.cwd()}/${out}`).pathname, { recursive: true });
fs.writeFileSync(out, JSON.stringify(json));
const kept = SECTIONS.reduce((n, [, lo, hi]) => n + hi - lo + 1, 0);
console.log(`${out}: ${Object.keys(sections).length} sections, ${kept} bytes; ${ROOMS} rooms`);
