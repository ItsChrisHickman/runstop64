import { Surface } from './surface';

/**
 * 8×8 bitmap font. Glyphs can come from an original game's charset (by ASCII
 * code) and be topped up with the kit's own glyphs for anything missing.
 */
export class BitmapFont {
  readonly glyphs = new Map<number, Uint8Array>();

  /** Take glyphs for the given ASCII codes from a C64 charset (char N at N*8). */
  addFromCharset(charset: Uint8Array, codes: Iterable<number>) {
    for (const c of codes) {
      const g = charset.subarray(c * 8, c * 8 + 8);
      if (g.some((b) => b)) this.glyphs.set(c, Uint8Array.from(g));
    }
    return this;
  }

  /** Take glyphs for the given characters from a charset via a game-specific char→code mapping. */
  addFromCharsetMapped(charset: Uint8Array, chars: string, toCode: (ascii: number) => number) {
    for (const ch of chars) {
      const c = toCode(ch.charCodeAt(0));
      const g = charset.subarray(c * 8, c * 8 + 8);
      // (an empty or solid cell isn't a letter: the charset hasn't got this one)
      if ((g.some((b) => b) && !g.every((b) => b === 0xff)) || ch === ' ') this.glyphs.set(ch.charCodeAt(0), Uint8Array.from(g));
    }
    return this;
  }

  /** Add glyphs drawn as 8 rows of '#'/'.' strings; existing glyphs are kept unless `replace`. */
  addDrawn(drawn: Record<string, string[]>, replace = false) {
    for (const [ch, rows] of Object.entries(drawn)) {
      const code = ch.charCodeAt(0);
      if (!replace && this.glyphs.has(code)) continue;
      const g = new Uint8Array(8);
      rows.forEach((row, i) => {
        for (let x = 0; x < 8; x++) if (row[x] === '#') g[i] |= 0x80 >> x;
      });
      this.glyphs.set(code, g);
    }
    return this;
  }

  glyph(ch: string): Uint8Array | undefined {
    return this.glyphs.get(ch.toUpperCase().charCodeAt(0));
  }

  /** Draw text at pixel position; returns the x after the last glyph. */
  draw(surface: Surface, text: string, x: number, y: number, colour: number) {
    for (const ch of text) {
      const g = this.glyph(ch);
      if (g) surface.drawChar(g, x, y, colour);
      x += 8;
    }
    return x;
  }

  /** Draw text centred on the surface at row y. */
  drawCentred(surface: Surface, text: string, y: number, colour: number) {
    this.draw(surface, text, Math.floor((surface.width - text.length * 8) / 2), y, colour);
  }
}

